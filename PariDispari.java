public class PariDispari {
    public static void main(String[] args) {
        int numero = 0; 

        if (numero % 2 == 0) {
            System.out.println(numero + " è un numero pari.");
        } else {
            System.out.println(numero + " è un numero dispari.");
        }
        System.out.println(-3 % 2);
    }
}
